/**
 * Helper to fetch from https://fakestoreapi.com/products and map to our schema
 * If the API is unreachable, times out, or returns fewer items, returns our rich local fallback.
 */
export async function fetchDemoProductsFromApi(): Promise<Product[]> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4000);
    const res = await fetch('https://fakestoreapi.com/products', { signal: controller.signal });
    clearTimeout(timeoutId);

    if (!res.ok) {
      throw new Error(`API returned status ${res.status}`);
    }

    const data = await res.json();
    if (Array.isArray(data) && data.length >= 10) {
      // Map FakeStore products into Indian Rupee e-commerce items
      const mapped = data.map((item: any, index: number): Product => {
        // category mapping
        let cat = 'fashion';
        if (item.category === 'jewelery') cat = 'jewellery';
        else if (item.category === 'electronics') cat = 'electronics';
        else if (item.category === "women's clothing" || item.category === "men's clothing") cat = 'fashion';
        else cat = 'home-living';

        const inrPrice = Math.round(Number(item.price) * 80 + 300);
        const salePrice = Math.round(inrPrice * 0.8);

        return {
          id: `fakestore-${item.id}`,
          title: item.title,
          description: item.description,
          category: cat,
          sku: `DSS-FS-${String(item.id).padStart(3, '0')}`,
          price: inrPrice,
          salePrice: salePrice,
          stock: 15 + ((item.id * 7) % 30),
          rating: item.rating?.rate || 4.5,
          reviewCount: item.rating?.count || 24,
          image: item.image,
          images: [item.image],
          isFeatured: index < 4,
          isBestSeller: index % 3 === 0,
          isNewArrival: index % 2 === 0,
          isDemo: true,
          purchaseCost: Math.round(inrPrice * 0.45),
          sizes: cat === 'fashion' ? ['S', 'M', 'L', 'XL'] : undefined,
          colors: cat === 'fashion' ? ['Navy Blue', 'Black', 'White'] : undefined,
        };
      });

      // Ensure at least 20 items by combining or using fallback
      if (mapped.length >= 20) {
        return mapped;
      }
      // Combine with our fallback to reach 20+
      return [...mapped, ...INITIAL_PRODUCTS.slice(0, 20 - mapped.length)];
    }
  } catch (err) {
    console.info('FakeStoreAPI fetch failed or timed out; utilizing rich local fallback dataset:', err);
  }

  return INITIAL_PRODUCTS;
}
